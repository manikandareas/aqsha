#!/usr/bin/env node
// Bundle the builtin Agent Skills (packages/convex/skills/<name>/SKILL.md, the
// agentskills.io folder layout) into a generated TS module that Convex can
// import at SEED time. Convex functions run in an isolate and cannot read the
// filesystem at runtime, so the real .md files (the source of truth, portable
// to Claude Code / Codex / Gemini CLI) are inlined here at build time.
//
// Run via `bun run --filter '@aqsha/convex' skills:bundle` (also runs as part of
// `codegen`). The output is committed so deploys work without re-running it.

import {
  existsSync,
  readFileSync,
  readdirSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const skillsDir = join(here, "..", "skills");
const outFile = join(
  here,
  "..",
  "convex",
  "agent",
  "skills",
  "builtin",
  "generated.ts",
);

// kind === directory name → manifest kind.
const RESOURCE_DIRS = {
  references: "reference",
  assets: "asset",
  scripts: "script",
};

function listFiles(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).filter((f) => statSync(join(dir, f)).isFile()).sort();
}

const entries = [];
const folders = existsSync(skillsDir)
  ? readdirSync(skillsDir)
      .filter((f) => statSync(join(skillsDir, f)).isDirectory())
      .sort()
  : [];

for (const slug of folders) {
  const skillPath = join(skillsDir, slug, "SKILL.md");
  if (!existsSync(skillPath)) continue;
  const doc = readFileSync(skillPath, "utf8");
  const resources = [];
  for (const [dirName, kind] of Object.entries(RESOURCE_DIRS)) {
    for (const file of listFiles(join(skillsDir, slug, dirName))) {
      resources.push({
        path: `${dirName}/${file}`,
        kind,
        content: readFileSync(join(skillsDir, slug, dirName, file), "utf8"),
      });
    }
  }
  entries.push({ slug, doc, resources });
}

const banner = `// GENERATED by scripts/bundle-skills.mjs — do not edit by hand.
// Edit the SKILL.md files under packages/convex/skills/ and re-run
// \`bun run --filter '@aqsha/convex' skills:bundle\`. Convex functions cannot read
// the filesystem at runtime, so the builtin skills are inlined here for seeding.
`;

const body = `export type BuiltinSkillResource = {
  path: string;
  kind: "reference" | "asset" | "script";
  content: string;
};

export type BuiltinSkill = {
  slug: string;
  doc: string;
  resources: BuiltinSkillResource[];
};

export const BUILTIN_SKILLS: readonly BuiltinSkill[] = ${JSON.stringify(
  entries,
  null,
  2,
)};

// Raw SKILL.md documents, in catalog order (back-compat for the seed path).
export const BUILTIN_SKILL_DOCS: readonly string[] = BUILTIN_SKILLS.map(
  (skill) => skill.doc,
);
`;

writeFileSync(outFile, `${banner}\n${body}`);
console.log(
  `Bundled ${entries.length} builtin skill(s) → ${outFile.replace(`${join(here, "..")}/`, "")}`,
);
