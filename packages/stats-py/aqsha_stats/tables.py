def dw_bounds(n: int, k: int, alpha: float = 0.05) -> tuple[float, float, list[str]]:
    """Savin-White dL/dU lookup with linear interpolation on n. Returns (dL, dU, notes)."""
    if abs(alpha - 0.05) > 1e-9:
        raise AnalysisError("unsupported_alpha", "Tabel Durbin-Watson tersedia hanya untuk alpha 0,05.")
    if k not in DW_TABLE_ALPHA_05:
        raise AnalysisError(
            "k_out_of_range",
            f"Tabel Durbin-Watson tersedia untuk 1-5 variabel independen (k), diminta k={k}.",
        )
    rows = DW_TABLE_ALPHA_05[k]
    ns = sorted(rows)
    notes: list[str] = []
    if n < ns[0]:
        raise AnalysisError(
            "n_out_of_range",
            f"Tabel Durbin-Watson dimulai dari n={ns[0]}; data hanya memiliki n={n}.",
        )
    if n > ns[-1]:
        notes.append(
            f"n={n} melebihi cakupan tabel Savin-White (maks n={ns[-1]}); "
            f"digunakan nilai dL/dU untuk n={ns[-1]}."
        )
        n = ns[-1]
    if n in rows:
        dl, du = rows[n]
        return dl, du, notes
    lo = max(x for x in ns if x < n)
    hi = min(x for x in ns if x > n)
    w = (n - lo) / (hi - lo)
    dl = rows[lo][0] + w * (rows[hi][0] - rows[lo][0])
    du = rows[lo][1] + w * (rows[hi][1] - rows[lo][1])
    notes.append(
        f"n={n} tidak tersedia persis di tabel; dL/dU diinterpolasi linear antara n={lo} dan n={hi}."
    )
    return dl, du, notes
