def r_tabel(n: int, alpha: float = 0.05) -> float:
    """Critical Pearson r (two-tailed) derived from the t distribution, df = n - 2."""
    df = n - 2
    if df < 1:
        raise AnalysisError("insufficient_data", "r tabel membutuhkan n minimal 3.")
    t = stats.t.ppf(1 - alpha / 2, df)
    return t / math.sqrt(df + t * t)


